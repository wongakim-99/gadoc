import {test,expect} from 'playwright/test';
import {createWorkspaceFixture,jsonFetch} from './support/slacord-api';
import {loginWithSession} from './support/slacord-session';
test('database surface starts with content and contextual tools; new rows need no setup form',async({page})=>{
  const f=await createWorkspaceFixture();
  const call=async<T>(path:string,body?:unknown,method=body?'POST':'GET')=>(await jsonFetch<T>(`/team/${f.teamId}${path}`,{token:f.owner.token,body,method}))!.data!;
  const db=await call<{id:string}>('/database',{name:'제품 개발 · 프로젝트'});
  for(const title of ['고객 인터뷰 정리','제품 요구사항','10월 출시 체크리스트'])await call(`/database/${db.id}/row/page`,{title,creationId:crypto.randomUUID().replaceAll('-','').slice(0,24),values:{status:'초안'}});
  await call(`/document/${f.documentId}`,{title:'프로젝트 홈',contentFormat:'json',content:JSON.stringify([{type:'heading',props:{level:2},content:[{type:'text',text:'진행 중인 프로젝트',styles:{}}]},{type:'database',props:{databaseId:db.id}},{type:'paragraph'}])},'PATCH');
  await loginWithSession(page,f.owner);await page.goto(`/${f.teamId}/docs/${f.documentId}`);
  const block=page.locator('[data-inline-database]');
  await expect(block.getByRole('table')).toBeVisible();
  await expect(page.getByText('열 설정',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'CSV 가져오기',exact:true})).toHaveCount(0);
  await page.screenshot({path:'docs/design-system/assets/database-surface-refined.png',fullPage:true});
  await block.getByRole('button',{name:'새 페이지 추가',exact:true}).click();
  const title=block.getByLabel('제목 없음 페이지 이름');
  await expect(title).toBeFocused();await title.fill('새 프로젝트');await title.press('Enter');
  await expect(block.getByLabel('새 프로젝트 페이지 이름')).toHaveValue('새 프로젝트');
  await block.getByLabel('데이터베이스 제목',{exact:true}).fill('제품 개발 프로젝트');
  await block.getByLabel('데이터베이스 제목',{exact:true}).press('Enter');
  await expect.poll(async()=> (await call<{name:string}>(`/database/${db.id}`)).name).toBe('제품 개발 프로젝트');
  await block.getByRole('button',{name:'보기 옵션',exact:true}).click();
  const menu=page.getByRole('dialog',{name:'보기 옵션',exact:true});
  await expect(menu.getByLabel('레이아웃',{exact:true})).toBeVisible();
  await expect(menu.getByText('열 설정',{exact:true})).toBeVisible();
  await page.keyboard.press('Escape');await expect(menu).toHaveCount(0);
  await block.getByRole('button',{name:'속성 추가',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
});
