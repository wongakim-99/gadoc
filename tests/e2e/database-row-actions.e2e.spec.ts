import {test,expect} from 'playwright/test';
import {createWorkspaceFixture,jsonFetch} from './support/slacord-api';
import {loginWithSession} from './support/slacord-session';
import type {DatabaseDetail,DatabaseProperty} from '../../packages/web/src/features/database/model/types';
test('row context menu duplicates content and values with a new ID and archives reversibly',async({page})=>{
  const f=await createWorkspaceFixture();
  const call=async<T>(path:string,body?:unknown,method=body?'POST':'GET')=>(await jsonFetch<T>(`/team/${f.teamId}${path}`,{token:f.owner.token,body,method}))!.data!;
  const db=await call<{id:string}>('/database',{name:'Page actions'}),api=`/database/${db.id}`;
  const prop=await call<DatabaseProperty>(`${api}/property`,{name:'ID',type:'unique_id',revision:0,prefix:'TASK'});
  const content=JSON.stringify([{type:'paragraph',content:[{type:'text',text:'Original notes',styles:{}}]}]);
  await call(`/document/${f.documentId}`,{title:'Original page',contentFormat:'json',content},'PATCH');
  await call(`${api}/row`,{documentId:f.documentId,values:{status:'검토 중'}});
  await loginWithSession(page,f.owner);await page.goto(`/${f.teamId}/docs?database=${db.id}`);
  const original=page.getByRole('row').filter({has:page.getByLabel('Original page 페이지 이름',{exact:true})});
  await original.click({button:'right'});
  const menu=page.getByRole('dialog',{name:'Original page 페이지 메뉴',exact:true});
  await menu.getByRole('button',{name:'복제',exact:true}).click();
  await expect(page.getByLabel('Original page (복사본) 페이지 이름',{exact:true})).toBeFocused();
  let detail=await call<DatabaseDetail>(api);expect(detail.rows).toHaveLength(2);
  const copy=detail.rows.find(row=>row.documentId!==f.documentId)!;
  expect(copy.values.status).toBe('검토 중');expect(copy.values[prop.id]).not.toBe(detail.rows.find(row=>row.documentId===f.documentId)!.values[prop.id]);
  expect((await call<{content:string}>(`/document/${copy.documentId}`)).content).toBe(content);
  await call(`${api}/row/${f.documentId}/duplicate`,{creationId:copy.documentId});expect((await call<DatabaseDetail>(api)).rows).toHaveLength(2);
  const copiedRow=page.getByRole('row').filter({has:page.getByLabel('Original page (복사본) 페이지 이름',{exact:true})});
  await copiedRow.click({button:'right'});await page.getByRole('button',{name:'휴지통으로 이동',exact:true}).click();
  await expect(page.getByLabel('Original page (복사본) 페이지 이름',{exact:true})).toHaveCount(0);
  await call(`/document/${copy.documentId}/restore`,{},'POST');
  await expect(page.getByLabel('Original page (복사본) 페이지 이름',{exact:true})).toBeVisible();
  detail=await call<DatabaseDetail>(api);expect(detail.rows.find(row=>row.documentId===copy.documentId)?.values[prop.id]).toBe(copy.values[prop.id]);
});
