import { test, expect } from 'playwright/test';
import { createWorkspaceFixture, jsonFetch } from './support/slacord-api';
import { loginWithSession } from './support/slacord-session';
import type { DatabaseDetail, DatabaseProperty } from '../../packages/web/src/features/database/model/types';

test('option colors and drag/keyboard ordering persist without changing selected values', async ({ page }) => {
    const f = await createWorkspaceFixture();
    const root = `/team/${f.teamId}/database`;
    const db = (await jsonFetch<{ id: string }>(root, { method: 'POST', token: f.owner.token, body: { name: '옵션 표시' } }))!.data!;
    const call = <T>(path: string, body?: unknown, method = body ? 'POST' : 'GET') => jsonFetch<T>(`${root}/${db.id}${path}`, { token: f.owner.token, body, method });
    const prop = (await call<DatabaseProperty>('/property', { name: '분류', type: 'multi_select', options: ['기획', '개발', '검토'], revision: 0 }))!.data!;
    await call('/row', { documentId: f.documentId });
    await call(`/row/${f.documentId}/${prop.id}`, { value: ['기획', '개발'], revision: 0 }, 'PATCH');
    await expect(call(`/property/${prop.id}/configuration`, { name: '분류', type: 'multi_select', options: ['기획', '개발', '검토'], optionColors: [{ name: '기획', color: 'invalid' }], revision: 1 }, 'PATCH')).rejects.toThrow('400');
    await loginWithSession(page, f.owner);
    await page.goto(`/${f.teamId}/docs?database=${db.id}`);
    await page.getByRole('button', { name: '분류 속성 편집', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '속성 설정' });
    await dialog.getByLabel('기획 색상', { exact: true }).selectOption('blue');
    await dialog.getByLabel('개발 색상', { exact: true }).selectOption('green');
    await dialog.getByRole('button', { name: '검토 순서 이동', exact: true }).press('ArrowUp');
    await dialog.getByRole('button', { name: '개발 순서 이동', exact: true }).dragTo(dialog.getByRole('button', { name: '기획 순서 이동', exact: true }));
    await dialog.getByRole('button', { name: '변경 적용' }).click();
    await expect(dialog).not.toBeVisible();
    let read = (await call<DatabaseDetail>(''))!.data!;
    expect(read.properties.find(p => p.id === prop.id)?.options).toEqual(['개발', '기획', '검토']);
    expect(read.rows[0].values[prop.id]).toEqual(['기획', '개발']);
    await page.reload();
    const tag = page.getByRole('table').getByText('기획', { exact: true });
    await expect(tag).toBeVisible();
    const initialColor = await tag.evaluate(el => getComputedStyle(el).backgroundColor);
    expect(initialColor).not.toBe('rgba(0, 0, 0, 0)');
    await page.getByRole('button', { name: / · 분류$/ }).click();
    await page.getByLabel('분류 검색', { exact: true }).fill('문서');
    await page.getByRole('button', { name: /문서.*만들기/ }).click();
    await page.keyboard.press('Escape');
    await expect.poll(async () => (await call<DatabaseDetail>(''))!.data!.properties.find(p => p.id === prop.id)?.options).toContain('문서');
    read = (await call<DatabaseDetail>(''))!.data!;
    expect(read.properties.find(p => p.id === prop.id)?.optionColors).toEqual([{ name: '기획', color: 'blue' }, { name: '개발', color: 'green' }]);
    await page.reload();
    await expect(tag).toHaveCSS('background-color', initialColor);
});
