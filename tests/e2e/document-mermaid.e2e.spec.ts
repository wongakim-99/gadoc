import { test, expect } from 'playwright/test';
import { createWorkspaceFixture, createGuestSessionForTeam, jsonFetch } from './support/slacord-api';
import { loginWithSession } from './support/slacord-session';

test('Mermaid slash blocks preview, persist shared edits and retain invalid source without executing links', async ({ page, browser }) => {
    test.setTimeout(90000);
    const f = await createWorkspaceFixture();
    await loginWithSession(page, f.owner);
    await page.goto(`/${f.teamId}/docs/${f.documentId}`);
    await page.locator('.bn-editor[contenteditable="true"]').click();
    await page.keyboard.press('Control+End');
    await page.keyboard.press('Enter');
    await page.keyboard.type('/mermaid');
    await page.getByRole('option', { name: /Mermaid 다이어그램/ }).click();
    const block = page.getByRole('region', { name: 'Mermaid 다이어그램' });
    const preview = block.getByRole('img', { name: 'Mermaid 다이어그램 미리보기' });
    await expect(preview).toBeVisible();
    await block.getByRole('button', { name: '코드', exact: true }).click();
    const code = block.getByRole('textbox', { name: 'Mermaid 코드' });
    const source = 'flowchart LR\n A[검토] --> B[완료]';
    await code.fill(source);
    await expect.poll(async () => (await jsonFetch<{content:string}>(`/team/${f.teamId}/document/${f.documentId}`, { token: f.owner.token }))?.data?.content ?? '').toContain('검토');
    await page.reload();
    await expect(preview).toBeVisible();
    await block.getByRole('button', { name: '코드', exact: true }).click();
    await expect(code).toHaveValue(source);
    await code.fill('flowchart LR\n A --> B\n click A "https://example.com"');
    await expect(block.getByRole('alert')).toBeVisible();
    await expect(code).toHaveValue(/https:\/\/example.com/);
    await expect(block.getByRole('link', { name: 'SVG 다운로드' })).toHaveCount(0);
    await code.fill(source);
    await block.getByRole('button', { name: '미리보기', exact: true }).click();
    await expect(preview).toBeVisible();
    await expect(block.getByRole('link', { name: 'SVG 다운로드' })).toHaveAttribute('download', 'diagram.svg');
    await block.getByRole('button', { name: '다이어그램 확대', exact: true }).click();
    await expect(block.getByRole('button', { name: '다이어그램 배율 초기화' })).toHaveText('125%');
    const downloadPromise = page.waitForEvent('download');
    await block.getByRole('link', { name: 'SVG 다운로드' }).click();
    const download = await downloadPromise;
    expect(download.suggestedFilename()).toBe('diagram.svg');
    await page.screenshot({path: test.info().outputPath('mermaid-preview.png')});
    const guest = await createGuestSessionForTeam({ teamId: f.teamId, ownerToken: f.owner.token });
    const context = await browser.newContext();
    try {
        const other = await context.newPage();
        await loginWithSession(other, f.actor);
        await other.goto(`/${f.teamId}/docs/${f.documentId}`);
        const peer = other.getByRole('region', { name: 'Mermaid 다이어그램' });
        await peer.getByRole('button', { name: '코드', exact: true }).click();
        await peer.getByRole('textbox', { name: 'Mermaid 코드' }).fill('sequenceDiagram\n Alice->>Bob: 공동 편집');
        await block.getByRole('button', { name: '코드', exact: true }).click();
        await expect(code).toHaveValue('sequenceDiagram\n Alice->>Bob: 공동 편집');
        await loginWithSession(other, guest);
        await other.goto(`/${f.teamId}/docs/${f.documentId}`);
        await expect(other.getByRole('img', { name: 'Mermaid 다이어그램 미리보기' })).toBeVisible();
        await other.getByRole('region', { name: 'Mermaid 다이어그램' }).getByRole('button', { name: '코드', exact: true }).click();
        await expect(other.getByRole('textbox', { name: 'Mermaid 코드' })).not.toBeEditable();
    } finally { await context.close(); }
});
