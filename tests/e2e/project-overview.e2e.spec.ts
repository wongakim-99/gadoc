import { test, expect } from 'playwright/test';
import { createWorkspaceFixture, createChannel, jsonFetch, sendSocketMessage } from './support/slacord-api';
import { loginWithSession } from './support/slacord-session';

test('workspace overview uses authorized project data and opens matching filters on mobile', async ({ page, browser }) => {
    const f = await createWorkspaceFixture();
    const call = <T>(path: string, body?: unknown, method = body ? 'POST' : 'GET') => jsonFetch<T>(`/team/${f.teamId}${path}`, { token: f.owner.token, body, method });
    const secondChannel = await createChannel({ teamId: f.teamId, token: f.owner.token, name: 'second-scope' });
    const doc = (await call<{ id: string }>('/document', { title: '비공개 업무 문서' }))!.data!;
    await call(`/document/${doc.id}`, { visibility: 'restricted', editPolicy: 'owner_admin', allowedViewerIds: [], allowedEditorIds: [] }, 'PATCH');
    const a = (await call<{ id: string }>('/project', { name: '업무 A', channelIds: [f.channelId], documentId: f.documentId }))!.data!;
    const b = (await call<{ id: string }>('/project', { name: '업무 B', channelIds: [secondChannel], documentId: doc.id }))!.data!;
    await call('/issue', { title: '내 A 작업', projectId: a.id, status: 'todo', assigneeIds: [f.owner.userId] });
    await call('/issue', { title: '동료 A 작업', projectId: a.id, status: 'in_progress', assigneeIds: [f.actor.userId] });
    await call('/issue', { title: '완료 B 작업', projectId: b.id, status: 'done', assigneeIds: [f.owner.userId] });
    await sendSocketMessage({ session: f.owner, teamId: f.teamId, channelId: f.channelId, content: '홈 최근 대화 확인' });
    await loginWithSession(page, f.owner);
    await page.goto(`/${f.teamId}`);
    const home = page.locator('[aria-label="업무 현황"]');
    await expect(home.getByRole('link', { name: '완료 이슈 1개', exact: true })).toBeVisible();
    await home.getByLabel('현황 업무 그룹').selectOption(a.id);
    await expect(home.getByRole('link', { name: '완료 이슈 0개', exact: true })).toBeVisible();
    await expect(home.getByRole('link', { name: '내 A 작업', exact: false })).toBeVisible();
    await expect(home.getByText('비공개 업무 문서', { exact: true })).toHaveCount(0);
    await home.getByLabel('내 담당만').check();
    await expect(home.getByRole('link', { name: '진행 중 이슈 0개', exact: true })).toBeVisible();
    await home.getByLabel('현황 기간').selectOption('7');
    await home.getByRole('link', { name: '할 일 이슈 1개', exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`project=${a.id}`));
    await expect(page).toHaveURL(/filterStatus=todo/);
    await expect(page).toHaveURL(/updatedAfter=/);
    await expect(page.getByRole('combobox', { name: '상태 필터', exact: true })).toContainText('할 일');
    await expect(page.getByRole('button', { name: '기간 해제', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '기간 해제', exact: true }).click();
    await expect(page).not.toHaveURL(/updatedAfter=/);
    await page.goto(`/${f.teamId}`);
    await expect(home.getByLabel('현황 업무 그룹')).toHaveValue(a.id);
    await page.clock.setFixedTime(new Date(Date.now() + 60 * 86400000));
    await home.getByRole('button', { name: '현황 새로고침' }).click();
    await home.getByLabel('현황 기간').selectOption('7');
    await expect(home.getByRole('link', { name: '할 일 이슈 0개', exact: true })).toBeVisible();
    await home.getByLabel('현황 기간').selectOption('');
    await expect(home.getByRole('link', { name: '할 일 이슈 1개', exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath('project-overview-mobile.png') });
    const context = await browser.newContext();
    const actor = await context.newPage();
    await loginWithSession(actor, f.actor);
    await actor.goto(`/${f.teamId}`);
    await expect(actor.locator('[aria-label="업무 현황"]').getByText('동료 A 작업', { exact: true })).toBeVisible();
    await expect(actor.locator('[aria-label="업무 현황"]').getByText('비공개 업무 문서', { exact: true })).toHaveCount(0);
    await context.close();
    await page.route(`**/api/team/${f.teamId}/issue`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: '현황 조회 실패' }) }));
    await home.getByRole('button', { name: '현황 새로고침' }).click();
    await expect(home.getByRole('alert')).toBeVisible();
    await expect(home.getByRole('link', { name: /이슈 \d+개/ })).toHaveCount(0);
    await page.unroute(`**/api/team/${f.teamId}/issue`);
    await home.getByRole('button', { name: '현황 새로고침' }).click();
    await expect(home.getByRole('link', { name: '할 일 이슈 1개', exact: true })).toBeVisible();
});
