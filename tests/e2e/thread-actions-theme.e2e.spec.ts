import { test, expect } from 'playwright/test';
import { createWorkspaceFixture, sendSocketMessage } from './support/slacord-api';
import { loginWithSession } from './support/slacord-session';

test('thread replies retain actions and deletion while the chosen theme survives reload', async ({ page }) => {
    test.setTimeout(90000);
    const f = await createWorkspaceFixture();
    const parent = await sendSocketMessage({ session: f.owner, teamId: f.teamId,
        channelId: f.channelId, content: '스레드 메뉴 검증 원문' });
    await loginWithSession(page, f.owner);
    await page.goto(`/${f.teamId}/channel/${f.channelId}`);
    const openThread = async () => {
        const row = page.locator(`#message-${parent.id}`);
        await row.focus();
        await row.getByRole('button', { name: '스레드', exact: true }).click();
    };
    await openThread();
    const thread = page.getByRole('complementary', { name: '스레드', exact: true });
    const composer = thread.locator('textarea');
    await composer.fill('답글 메뉴 검증');
    await composer.press('Enter');
    await expect(thread.locator('[data-message-id]').filter({ hasText: '답글 메뉴 검증' })).toBeVisible();
    // Fetch an existing reply after remount, rather than testing only optimistic messages.
    await page.reload();
    await openThread();
    const reply = thread.locator('[data-message-id]').filter({ hasText: '답글 메뉴 검증' });
    await expect(reply).toBeVisible();
    const replyId = await reply.getAttribute('data-message-id');
    const row = thread.locator(`[data-message-id="${replyId}"]`);
    await row.focus();
    await row.getByRole('button', { name: '리액션', exact: true }).click();
    await page.getByRole('dialog', { name: '리액션 선택', exact: true }).getByRole('button', { name: '👍 좋아요', exact: true }).click();
    await expect(row.getByRole('button', { name: '👍 1', exact: true })).toBeVisible();
    await row.hover();
    await row.getByRole('button', { name: '편집', exact: true }).click();
    await row.locator('textarea').fill('수정된 스레드 답글');
    await row.locator('textarea').press('Enter');
    await expect(row).toContainText('수정된 스레드 답글');
    await row.focus();
    await row.getByRole('button', { name: '메시지 후속 업무', exact: true }).click();
    await expect(row.getByRole('button', { name: '이 메시지에서 이슈 만들기' })).toBeVisible();
    await row.getByRole('button', { name: '메시지 후속 업무', exact: true }).click();
    page.on('dialog', (dialog) => dialog.accept());
    await row.getByRole('button', { name: '삭제', exact: true }).click();
    await expect(row).toHaveCount(0);
    await thread.getByRole('button', { name: '스레드 닫기' }).click();
    await openThread();
    await expect(thread.locator(`[data-message-id="${replyId}"]`)).toHaveCount(0);
    await thread.getByRole('button', { name: '스레드 닫기' }).click();
    await page.getByRole('button', { name: '사용자 메뉴', exact: true }).click();
    await page.getByRole('button', { name: '라이트 테마', exact: true }).click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    await page.reload();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    await expect(page.locator('.workspace-shell').first()).toHaveCSS('background-color', 'rgb(255, 255, 255)');
    const captureRoot = process.env.TEMP || test.info().outputDir;
    await page.screenshot({ path: `${captureRoot}/gadoc-light-chat.png` });
    await page.goto(`/${f.teamId}/docs/${f.documentId}`);
    await expect(page.getByRole('textbox', { name: '페이지 제목' })).toBeVisible();
    await expect(page.locator('.bn-editor')).toBeVisible();
    await page.screenshot({ path: `${captureRoot}/gadoc-light-document.png` });
    await page.goto('/dashboard');
    await expect(page.getByText(f.teamName, { exact: true }).first()).toBeVisible();
    await page.screenshot({ path: `${captureRoot}/gadoc-light-dashboard.png` });
    await page.goto(`/${f.teamId}/channel/${f.channelId}`);
    await page.getByRole('button', { name: '사용자 메뉴', exact: true }).click();
    await page.getByRole('button', { name: '다크 테마', exact: true }).click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
});
