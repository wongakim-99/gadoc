import { test, expect } from 'playwright/test';
import { createWorkspaceFixture, jsonFetch } from './support/slacord-api';
import { loginWithSession } from './support/slacord-session';
import type { DatabaseDetail, DatabaseProperty } from '../../packages/web/src/features/database/model/types';

test('numeric progress persists presentation, edits raw values and keeps formula results', async ({ page }) => {
    const f = await createWorkspaceFixture();
    const root = `/team/${f.teamId}/database`;
    const db = (await jsonFetch<{ id: string }>(root, { method: 'POST', token: f.owner.token, body: { name: '진행률' } }))!.data!;
    const call = <T>(path: string, body?: unknown, method: 'POST' | 'GET' | 'PATCH' = body ? 'POST' : 'GET') => jsonFetch<T>(`${root}/${db.id}${path}`, { token: f.owner.token, body, method });
    const settings = { display: 'bar', divideBy: 100, color: 'blue', showNumber: true };
    const prop = (await call<DatabaseProperty>('/property', { name: '진척', type: 'number', numberPresentation: settings, revision: 0 }))!.data!;
    const formula = (await call<DatabaseProperty>('/property', { name: '두 배', type: 'formula', formula: 'prop("진척") * 2', numberPresentation: { ...settings, display: 'ring' }, revision: 1 }))!.data!;
    await call('/row', { documentId: f.documentId });
    await call(`/row/${f.documentId}/${prop.id}`, { value: 25, revision: 0 }, 'PATCH');
    await expect(call('/property', { name: '잘못된 기준', type: 'number', numberPresentation: { ...settings, divideBy: 0 }, revision: 2 })).rejects.toThrow('400');
    await expect(call('/property', { name: '잘못된 타입', type: 'text', numberPresentation: settings, revision: 2 })).rejects.toThrow('400');
    await loginWithSession(page, f.owner);
    await page.goto(`/${f.teamId}/docs?database=${db.id}`);
    const progress = page.getByRole('progressbar', { name: / · 진척 진행률$/ });
    await expect(progress).toHaveAttribute('aria-valuenow', '25');
    const cell = page.getByLabel(/ · 진척$/);
    await expect(cell).toHaveCSS('color', 'rgba(0, 0, 0, 0)');
    await cell.focus();
    await expect(progress).toHaveCount(0);
    await expect(cell).toHaveValue('25');
    await cell.fill('75'); await cell.press('Tab');
    await expect(progress).toHaveAttribute('aria-valuenow', '75');
    await page.getByRole('button', { name: '진척 속성 편집', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '속성 설정' });
    await dialog.getByLabel('표시 방식', { exact: true }).selectOption('ring');
    await dialog.getByLabel('기준값', { exact: true }).fill('200');
    await dialog.getByLabel('숫자 함께 표시').uncheck();
    await dialog.getByRole('button', { name: '변경 적용' }).click();
    await expect(progress).toHaveAttribute('aria-valuenow', '37.5');
    await expect(progress.locator('svg')).toBeVisible();
    await expect(progress).toHaveText('');
    await page.reload();
    await expect(progress).toHaveAttribute('aria-valuenow', '37.5');
    const read = (await call<DatabaseDetail>(''))!.data!;
    expect(read.rows[0].values[prop.id]).toBe(75);
    expect(read.rows[0].values[formula.id]).toBe(150);
    expect(read.properties.find(p => p.id === prop.id)?.numberPresentation).toEqual({ ...settings, display: 'ring', divideBy: 200, showNumber: false });
});
